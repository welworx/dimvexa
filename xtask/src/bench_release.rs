//! `cargo xtask bench-release`: the full benchmark of the version being released, and nothing else.
//!
//! ```text
//! cargo xtask bench-release                 # every row of m0.rs on the working tree, 6 runs
//! cargo xtask bench-release --runs 8        # more runs (at least 3)
//! cargo xtask bench-release --replace       # also replace a report that bench-matrix wrote
//! ```
//!
//! Run it once, when a release is prepared, on the release commit. It measures **every row** of
//! `crates/dimvexa/benches/m0.rs` (not only the guarded ones) on this working tree, `--runs`
//! times in a row, and writes `docs/benchmarks/vX.Y.Z.md` with the machine, compiler, profile,
//! bench file revision, commit, and the median and spread of every row. It does **not** build or
//! run any older version, so it takes about one minute per run, and it does not touch
//! `matrix.md` or `matrix-raw.tsv`.
//!
//! The report has no comparison column: numbers from another day, machine or bench file are never
//! put in one table (`benchmarks` skill). What a change cost is answered when it is made, by
//! `cargo xtask bench-impact`; a side-by-side table of released versions is the manual
//! `cargo xtask bench-matrix`. A file for this version that was written by hand is kept; a narrative goes in `vX.Y.Z-notes.md`.
#![allow(
    clippy::arithmetic_side_effects,
    clippy::cast_precision_loss,
    clippy::float_arithmetic
)]

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;
use std::process::ExitCode;

use crate::bench_check::{Rows, git, run_bench_in};
use crate::bench_matrix::{cargo_version, command_line, cpu, fmt_ns, stat};

const BENCH_FILE: &str = "crates/dimvexa/benches/m0.rs";
pub const MARKER: &str = "<!-- generated by cargo xtask bench-release; do not edit by hand -->";
/// The marker of `bench-matrix`: a report it wrote may be replaced by a fresh full run.
const MATRIX_MARKER: &str = "<!-- generated by cargo xtask bench-matrix; do not edit by hand -->";
const DEFAULT_RUNS: usize = 6;

/// `--runs N` and `--replace` (allow replacing a report that `bench-matrix` wrote).
fn parse_opts(args: &[String]) -> Result<(usize, bool), String> {
    let mut runs = DEFAULT_RUNS;
    let mut replace = false;
    let mut it = args.iter();
    while let Some(a) = it.next() {
        match a.as_str() {
            "--replace" => replace = true,
            "--runs" => {
                runs = it
                    .next()
                    .and_then(|v| v.parse().ok())
                    .filter(|n| *n >= 3)
                    .ok_or(
                        "--runs needs a number of at least 3 (a median of fewer runs is not solid)",
                    )?;
            }
            other => return Err(format!("unknown option {other}")),
        }
    }
    Ok((runs, replace))
}

/// A report may be replaced if there is none or this tool wrote it. One that `bench-matrix` wrote
/// belongs to a measured release (side by side with its predecessor) and needs `--replace`; a
/// hand-written one is never replaced.
fn may_overwrite(existing: Option<&str>, replace: bool) -> bool {
    existing.is_none_or(|t| t.starts_with(MARKER) || (replace && t.starts_with(MATRIX_MARKER)))
}

fn report_md(
    version: &str,
    series: &BTreeMap<String, Vec<f64>>,
    meta: &str,
    runs: usize,
) -> String {
    let mut s = format!("{MARKER}\n# Benchmarks for {version}\n\n{meta}\n");
    let _ = writeln!(
        s,
        "Full run of every row of the bench file on the release commit, {runs} runs in a row. \
         The numbers are the median over the runs of each run's median ns/op; spread = (max - min) / median. \
         This report has no narrative: what changed in the code is in the CHANGELOG.\n"
    );
    let _ = writeln!(s, "| row | {version} (ns/op) | spread % |\n|---|---:|---:|");
    for (row, values) in series {
        let (median, spread) = stat(values);
        let _ = writeln!(s, "| {row} | {} | {spread:.0} |", fmt_ns(median));
    }
    s.push_str(
        "\nNot compared with earlier versions: numbers from another day, machine or bench file are not put in one table. \
         `cargo xtask bench-matrix` measures versions side by side when that is wanted; the cost of each change was \
         checked when it was made (`cargo xtask bench-impact`).\n\
         Not run: other machines, compilers or profiles; the cross-library comparison; the bindings.\n",
    );
    s
}

fn execute(args: &[String], root: &Path) -> Result<(), String> {
    let (runs, replace) = parse_opts(args)?;
    let version = cargo_version(root);
    let path = root
        .join("docs")
        .join("benchmarks")
        .join(format!("v{version}.md"));
    let existing = std::fs::read_to_string(&path).ok();
    if !may_overwrite(existing.as_deref(), replace) {
        return Err(format!(
            "docs/benchmarks/v{version}.md exists and was not written by bench-release (a hand-written \
             report is never replaced; one from bench-matrix needs --replace, and only for a version \
             that is being prepared, not a released one). Put a narrative in v{version}-notes.md instead."
        ));
    }
    let mut series: BTreeMap<String, Vec<f64>> = BTreeMap::new();
    for round in 1..=runs {
        println!("bench-release: run {round} of {runs}: {version} (about a minute)");
        let rows: Rows = run_bench_in(root, None)?;
        for (row, value) in rows {
            series.entry(row).or_default().push(value);
        }
    }
    let head = git(root, &["rev-parse", "--short", "HEAD"])?;
    let dirty = !git(
        root,
        &[
            "status",
            "--porcelain",
            "--",
            "crates",
            ".cargo",
            "Cargo.toml",
            "Cargo.lock",
            "rust-toolchain.toml",
        ],
    )?
    .is_empty();
    let bench_rev = git(root, &["log", "-1", "--format=%h", "--", BENCH_FILE])?;
    let meta = format!(
        "* Date: {}\n* Machine: {}, {}\n* Compiler: {}\n* Profile: `bench` (release, thin LTO)\n* Bench file: `{BENCH_FILE}` at {bench_rev}\n* Commit: {head}{}\n",
        command_line("date", &["+%F"]),
        cpu(),
        command_line("uname", &["-sr"]),
        command_line("rustc", &["--version"]),
        if dirty {
            " (+ uncommitted changes in the code)"
        } else {
            ""
        },
    );
    std::fs::write(&path, report_md(&version, &series, &meta, runs)).map_err(|e| e.to_string())?;
    println!(
        "bench-release: wrote docs/benchmarks/v{version}.md ({} rows, {runs} runs)",
        series.len()
    );
    if dirty {
        println!(
            "bench-release: the code has uncommitted changes; commit them and measure the release commit so the report names it"
        );
    }
    Ok(())
}

/// Entry point for `cargo xtask bench-release`.
pub fn run(args: &[String], root: &Path) -> ExitCode {
    match execute(args, root) {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("bench-release: {e}");
            ExitCode::FAILURE
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn runs_default_and_floor() {
        assert_eq!(parse_opts(&[]), Ok((DEFAULT_RUNS, false)));
        assert_eq!(
            parse_opts(&["--runs".into(), "8".into(), "--replace".into()]),
            Ok((8, true))
        );
        assert!(parse_opts(&["--runs".into(), "2".into()]).is_err());
        assert!(parse_opts(&["--all".into()]).is_err());
    }

    #[test]
    fn a_hand_written_report_is_kept() {
        assert!(may_overwrite(None, false));
        assert!(may_overwrite(Some(&format!("{MARKER}\n# x")), false));
        assert!(!may_overwrite(
            Some(&format!("{MATRIX_MARKER}\n# x")),
            false
        ));
        assert!(may_overwrite(Some(&format!("{MATRIX_MARKER}\n# x")), true));
        assert!(!may_overwrite(
            Some("# Benchmarks for 0.5.0\nhand written"),
            true
        ));
    }

    #[test]
    fn the_report_lists_every_row_with_its_spread() {
        let mut series = BTreeMap::new();
        series.insert("row a".to_string(), vec![10.0, 11.0, 12.0]);
        series.insert("row b".to_string(), vec![2.0, 2.0, 2.0]);
        let md = report_md("9.9.9", &series, "* Date: today\n", 3);
        assert!(md.starts_with(MARKER));
        assert!(md.contains("# Benchmarks for 9.9.9"));
        assert!(md.contains("| row a |") && md.contains("| row b |"));
        assert!(md.contains("Not compared with earlier versions"));
    }
}
