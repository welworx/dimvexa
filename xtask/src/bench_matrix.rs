//! `cargo xtask bench-matrix`: the `m0` bench on every released version, with ONE bench file.
//!
//! ```text
//! cargo xtask bench-matrix                  # every version in docs/benchmarks/releases.tsv, then the working tree
//! cargo xtask bench-matrix --runs 8         # runs per version (default 6)
//! cargo xtask bench-matrix --reports        # also (re)write the generated vX.Y.Z.md reports
//! cargo xtask bench-matrix --only 0.4.0     # only these versions (repeatable); the working tree stays
//! ```
//!
//! Why: a number is only comparable with another one if both came from the same bench file, the
//! same machine, the same compiler and the same hour. So the *current*
//! `crates/dimvexa/benches/m0.rs` is copied into a detached worktree of every release and run
//! there, round-robin (round r runs every version once), so slow drift of a shared VM hits all
//! versions alike. When a row is added to the bench, run this again: every release is re-measured
//! with the new row (the `benchmarks` skill makes that a rule).
//!
//! Output (`docs/benchmarks/`): `matrix.md` (medians, spread, change against the previous
//! version, marked when the change is inside the noise), `matrix-raw.tsv` (every run of every
//! row) and, with `--reports`, one generated `vX.Y.Z.md` per version (a file without the
//! generated marker is hand-written and is never overwritten). Versions whose build fails with the
//! current bench file are listed, not hidden.
//!
//! `docs/benchmarks/releases.tsv` is `version<TAB>commit`, one line per released version, oldest
//! first. The release skill adds a line when a version is released.
#![allow(
    clippy::arithmetic_side_effects,
    clippy::cast_precision_loss,
    clippy::indexing_slicing,
    clippy::float_arithmetic
)]

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::{Command, ExitCode};

use crate::bench_check::{Rows, git, run_bench_in};

const RELEASES: &str = "docs/benchmarks/releases.tsv";
const BENCH_FILE: &str = "crates/dimvexa/benches/m0.rs";
const MARKER: &str = "<!-- generated by cargo xtask bench-matrix; do not edit by hand -->";
const DEFAULT_RUNS: usize = 6;

struct Opts {
    runs: usize,
    reports: bool,
    only: Vec<String>,
}

fn parse_opts(args: &[String]) -> Result<Opts, String> {
    let mut o = Opts {
        runs: DEFAULT_RUNS,
        reports: false,
        only: Vec::new(),
    };
    let mut it = args.iter();
    while let Some(a) = it.next() {
        match a.as_str() {
            "--reports" => o.reports = true,
            "--runs" => {
                o.runs = it
                    .next()
                    .and_then(|v| v.parse().ok())
                    .filter(|n| *n >= 3)
                    .ok_or(
                        "--runs needs a number of at least 3 (a median of fewer runs is not solid)",
                    )?;
            }
            "--only" => o
                .only
                .push(it.next().ok_or("--only needs a version")?.clone()),
            other => return Err(format!("unknown option {other}")),
        }
    }
    Ok(o)
}

/// A version to measure: its label, and the worktree to run in.
struct Subject {
    label: String,
    commit: String,
    dir: PathBuf,
    /// A temporary worktree to remove afterwards (the working tree is not one).
    temporary: bool,
}

fn read_releases(root: &Path) -> Result<Vec<(String, String)>, String> {
    let text = std::fs::read_to_string(root.join(RELEASES))
        .map_err(|e| format!("cannot read {RELEASES}: {e}"))?;
    let mut out = Vec::new();
    for line in text
        .lines()
        .filter(|l| !l.trim().is_empty() && !l.starts_with('#'))
    {
        let (v, c) = line
            .split_once('\t')
            .ok_or_else(|| format!("{RELEASES}: '{line}' is not 'version<TAB>commit'"))?;
        out.push((v.trim().to_string(), c.trim().to_string()));
    }
    if out.is_empty() {
        return Err(format!("{RELEASES} lists no version"));
    }
    Ok(out)
}

fn cargo_version(root: &Path) -> String {
    std::fs::read_to_string(root.join("Cargo.toml"))
        .ok()
        .and_then(|t| {
            t.lines().find(|l| l.starts_with("version = ")).map(|l| {
                l.trim_start_matches("version = ")
                    .trim_matches('"')
                    .to_string()
            })
        })
        .unwrap_or_else(|| "working tree".to_string())
}

fn command_line(cmd: &str, args: &[&str]) -> String {
    Command::new(cmd).args(args).output().map_or_else(
        |_| "unknown".to_string(),
        |o| String::from_utf8_lossy(&o.stdout).trim().to_string(),
    )
}

fn cpu() -> String {
    let model = std::fs::read_to_string("/proc/cpuinfo")
        .ok()
        .and_then(|t| {
            t.lines()
                .find(|l| l.starts_with("model name"))
                .and_then(|l| l.split_once(':').map(|(_, m)| m.trim().to_string()))
        })
        .unwrap_or_else(|| "unknown CPU".to_string());
    let n = std::thread::available_parallelism().map_or(0, std::num::NonZero::get);
    format!("{model}, {n} logical CPUs")
}

fn median(v: &mut [f64]) -> f64 {
    v.sort_by(f64::total_cmp);
    v[v.len() / 2]
}

/// `(median of the run medians, spread in percent = (max - min) / median)`.
fn stat(values: &[f64]) -> (f64, f64) {
    let mut v = values.to_vec();
    let m = median(&mut v);
    let (lo, hi) = (v[0], v[v.len() - 1]);
    (m, if m > 0.0 { (hi - lo) / m * 100.0 } else { 0.0 })
}

/// A change in percent, marked when it is inside the larger of the two spreads (so it cannot be
/// told from the noise of this machine).
fn change(prev: (f64, f64), now: (f64, f64)) -> String {
    if prev.0 <= 0.0 {
        return "-".to_string();
    }
    let pct = (now.0 / prev.0 - 1.0) * 100.0;
    let noise = prev.1.max(now.1);
    if pct.abs() <= noise {
        format!("{pct:+.1}% (noise)")
    } else {
        format!("{pct:+.1}%")
    }
}

fn fmt_ns(v: f64) -> String {
    if v >= 1000.0 {
        format!("{v:.0}")
    } else {
        format!("{v:.3}")
    }
}

type Series = BTreeMap<String, BTreeMap<String, Vec<f64>>>; // version -> row -> runs

fn matrix_md(
    versions: &[String],
    series: &Series,
    failed: &[(String, String)],
    meta: &str,
    runs: usize,
) -> String {
    let mut rows: Vec<&String> = series
        .values()
        .flat_map(BTreeMap::keys)
        .collect::<std::collections::BTreeSet<_>>()
        .into_iter()
        .collect();
    rows.sort();
    let cell = |v: &str, r: &str| series.get(v).and_then(|m| m.get(r)).map(|x| stat(x));
    let mut s =
        format!("{MARKER}\n# Benchmark matrix: every released version, one bench file\n\n{meta}\n");
    let _ = writeln!(
        s,
        "Statistic: the median over {runs} runs of each run's median ns/op; spread = (max - min) / median of those runs. \
         Rounds alternate: round r runs every version once, in the order of the columns, so drift of the machine hits all of them. \
         A change marked `(noise)` is not larger than the spread of either side and says nothing about the code.\n"
    );
    if !failed.is_empty() {
        s.push_str("Versions that did not build or run with this bench file (not hidden):\n\n");
        for (v, e) in failed {
            let _ = writeln!(s, "* {v}: {}", e.lines().next().unwrap_or(""));
        }
        s.push('\n');
    }
    s.push_str("## Medians (ns/op), and the last version against the one before\n\n");
    let _ = writeln!(s, "| row | {} | change |", versions.join(" | "));
    let _ = writeln!(s, "|---|{}---:|", "---:|".repeat(versions.len()));
    for r in &rows {
        let cells: Vec<String> = versions
            .iter()
            .map(|v| cell(v, r).map_or_else(|| "-".to_string(), |c| fmt_ns(c.0)))
            .collect();
        let delta = if versions.len() >= 2 {
            match (
                cell(&versions[versions.len() - 2], r),
                cell(&versions[versions.len() - 1], r),
            ) {
                (Some(a), Some(b)) => change(a, b),
                _ => "-".to_string(),
            }
        } else {
            "-".to_string()
        };
        let _ = writeln!(s, "| {r} | {} | {delta} |", cells.join(" | "));
    }
    s.push_str("\n## Spread (percent of the median)\n\n");
    let _ = writeln!(s, "| row | {} |", versions.join(" | "));
    let _ = writeln!(s, "|---|{}", "---:|".repeat(versions.len()));
    for r in &rows {
        let cells: Vec<String> = versions
            .iter()
            .map(|v| cell(v, r).map_or_else(|| "-".to_string(), |c| format!("{:.0}", c.1)))
            .collect();
        let _ = writeln!(s, "| {r} | {} |", cells.join(" | "));
    }
    s
}

fn report_md(
    version: &str,
    prev: Option<&str>,
    series: &Series,
    meta: &str,
    runs: usize,
) -> String {
    let mut s = format!("{MARKER}\n# Benchmarks for {version}\n\n{meta}\n");
    let _ = writeln!(
        s,
        "Generated from the matrix run of `docs/benchmarks/matrix.md` (all versions, one bench file, {runs} alternating runs each). \
         The numbers are the median over the runs of each run's median ns/op; spread = (max - min) / median. \
         This report has no narrative: what changed in the code is in the CHANGELOG.\n"
    );
    let _ = writeln!(
        s,
        "| row | {version} (ns/op) | spread % | {} |\n|---|---:|---:|---:|",
        prev.map_or_else(|| "previous".to_string(), |p| format!("vs {p}"))
    );
    if let Some(mine) = series.get(version) {
        for (r, runs_v) in mine {
            let now = stat(runs_v);
            let delta = prev
                .and_then(|p| series.get(p))
                .and_then(|m| m.get(r))
                .map_or_else(|| "-".to_string(), |x| change(stat(x), now));
            let _ = writeln!(s, "| {r} | {} | {:.0} | {delta} |", fmt_ns(now.0), now.1);
        }
    }
    s.push_str("\nNot run: other machines, compilers or profiles; the cross-library comparison; the bindings.\n");
    s
}

fn execute(args: &[String], root: &Path) -> Result<(), String> {
    let o = parse_opts(args)?;
    let releases: Vec<(String, String)> = read_releases(root)?
        .into_iter()
        .filter(|(v, _)| o.only.is_empty() || o.only.contains(v))
        .collect();
    let bench_src = root.join(BENCH_FILE);
    let tmp_root = root.join("target").join("bench-matrix");
    let target = tmp_root.join("target");
    let _ = std::fs::create_dir_all(&tmp_root);
    let mut subjects: Vec<Subject> = Vec::new();
    for (v, c) in &releases {
        let commit = git(root, &["rev-parse", "--verify", &format!("{c}^{{commit}}")])?;
        let dir = tmp_root.join(v);
        let _ = git(
            root,
            &["worktree", "remove", "--force", &dir.to_string_lossy()],
        );
        let _ = std::fs::remove_dir_all(&dir);
        git(
            root,
            &[
                "worktree",
                "add",
                "--detach",
                &dir.to_string_lossy(),
                &commit,
            ],
        )?;
        std::fs::copy(&bench_src, dir.join(BENCH_FILE))
            .map_err(|e| format!("cannot copy the bench file into {v}: {e}"))?;
        subjects.push(Subject {
            label: v.clone(),
            commit,
            dir,
            temporary: true,
        });
    }
    let current = cargo_version(root);
    let head = git(root, &["rev-parse", "--short", "HEAD"])?;
    subjects.retain(|s| s.label != current);
    subjects.push(Subject {
        label: current.clone(),
        commit: format!("{head} (working tree)"),
        dir: root.to_path_buf(),
        temporary: false,
    });

    let mut series: Series = BTreeMap::new();
    let mut failed: Vec<(String, String)> = Vec::new();
    let mut alive: Vec<usize> = (0..subjects.len()).collect();
    for round in 1..=o.runs {
        let mut still = Vec::new();
        for &i in &alive {
            let s = &subjects[i];
            println!("bench-matrix: round {round} of {}: {}", o.runs, s.label);
            match run_bench_in(&s.dir, Some(&target)) {
                Ok(rows) => {
                    record(&mut series, &s.label, &rows);
                    still.push(i);
                }
                Err(e) if round == 1 => failed.push((s.label.clone(), e)),
                Err(e) => return Err(format!("{} failed in round {round}: {e}", s.label)),
            }
        }
        alive = still;
    }
    for s in subjects.iter().filter(|s| s.temporary) {
        let _ = git(
            root,
            &["worktree", "remove", "--force", &s.dir.to_string_lossy()],
        );
    }
    let _ = git(root, &["worktree", "prune"]);

    let versions: Vec<String> = subjects
        .iter()
        .filter(|s| series.contains_key(&s.label))
        .map(|s| s.label.clone())
        .collect();
    let dirty = !git(root, &["status", "--porcelain", "--", BENCH_FILE])?.is_empty();
    let bench_rev = git(root, &["log", "-1", "--format=%h", "--", BENCH_FILE])?;
    let commits: Vec<String> = subjects
        .iter()
        .map(|s| {
            format!(
                "{} = {}",
                s.label,
                if s.temporary {
                    s.commit.chars().take(7).collect::<String>()
                } else {
                    s.commit.clone()
                }
            )
        })
        .collect();
    let meta = format!(
        "* Date: {}\n* Machine: {}, {}\n* Compiler: {}\n* Profile: `bench` (release, thin LTO)\n* Bench file: `{BENCH_FILE}` at {bench_rev}{} copied into every version\n* Commits: {}\n",
        command_line("date", &["+%F"]),
        cpu(),
        command_line("uname", &["-sr"]),
        command_line("rustc", &["--version"]),
        if dirty {
            " (+ uncommitted changes)"
        } else {
            ""
        },
        commits.join(", "),
    );
    let dir = root.join("docs").join("benchmarks");
    std::fs::write(
        dir.join("matrix.md"),
        matrix_md(&versions, &series, &failed, &meta, o.runs),
    )
    .map_err(|e| e.to_string())?;
    let mut raw = String::from("version\trun\trow\tmedian_ns_per_op\n");
    for (v, rows) in &series {
        for (r, vals) in rows {
            for (i, x) in vals.iter().enumerate() {
                let _ = writeln!(raw, "{v}\t{}\t{r}\t{x}", i + 1);
            }
        }
    }
    std::fs::write(dir.join("matrix-raw.tsv"), raw).map_err(|e| e.to_string())?;
    println!("bench-matrix: wrote docs/benchmarks/matrix.md and matrix-raw.tsv");
    if o.reports {
        for (i, v) in versions.iter().enumerate() {
            let path = dir.join(format!("v{v}.md"));
            let hand_written = std::fs::read_to_string(&path).is_ok_and(|t| !t.starts_with(MARKER));
            if hand_written {
                println!("bench-matrix: kept the hand-written v{v}.md");
                continue;
            }
            let prev = i.checked_sub(1).map(|j| versions[j].as_str());
            std::fs::write(&path, report_md(v, prev, &series, &meta, o.runs))
                .map_err(|e| e.to_string())?;
            println!("bench-matrix: wrote v{v}.md");
        }
    }
    Ok(())
}

fn record(series: &mut Series, label: &str, rows: &Rows) {
    let m = series.entry(label.to_string()).or_default();
    for (k, v) in rows {
        m.entry(k.clone()).or_default().push(*v);
    }
}

/// Entry point for `cargo xtask bench-matrix`.
pub fn run(args: &[String], root: &Path) -> ExitCode {
    match execute(args, root) {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("bench-matrix: {e}");
            ExitCode::FAILURE
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn stat_is_median_and_spread() {
        let (m, s) = stat(&[10.0, 12.0, 11.0, 10.5, 11.5]);
        assert!((m - 11.0).abs() < 1e-12);
        assert!((s - 200.0 / 11.0).abs() < 1e-9);
    }

    #[test]
    fn a_change_inside_the_noise_is_marked() {
        assert_eq!(change((100.0, 8.0), (105.0, 3.0)), "+5.0% (noise)");
        assert_eq!(change((100.0, 3.0), (130.0, 4.0)), "+30.0%");
        assert_eq!(change((0.0, 0.0), (1.0, 0.0)), "-");
    }

    #[test]
    fn runs_below_three_are_refused() {
        assert!(parse_opts(&["--runs".into(), "2".into()]).is_err());
        assert_eq!(
            parse_opts(&["--runs".into(), "6".into(), "--reports".into()])
                .map(|o| (o.runs, o.reports)),
            Ok((6, true))
        );
    }
}
