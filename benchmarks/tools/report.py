"""Turn benchmarks/results/*.json into docs/benchmarks/comparison.md plus SVG bar charts.

Standard library only. It never invents a number: every figure is read from a result file. With no
result files it writes a notice that no run has been published. Fixture files (`"fixture": true`,
used only to test this script) produce output that is labelled as fixture data on every table and
chart and can never be written to the official path.

    python3 benchmarks/tools/report.py                       # results/ -> docs/benchmarks/comparison.md
    python3 benchmarks/tools/report.py --results benchmarks/fixtures/results --out /tmp/x/comparison.md
"""
import argparse
import html
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REPO = ROOT.parent
OFFICIAL = REPO / "docs" / "benchmarks" / "comparison.md"
FIXTURE_BANNER = "**FIXTURE DATA: these numbers are made up to test the report generator. They are not measurements of any library.**"


def load(results_dir):
    files = sorted(Path(results_dir).glob("*.json"))
    out = []
    for f in files:
        try:
            d = json.loads(f.read_text())
        except (OSError, ValueError) as e:
            raise SystemExit(f"{f}: cannot read: {e}")
        if d.get("schema") != "dimvexa.bench.result/1":
            raise SystemExit(f"{f}: unknown schema {d.get('schema')!r}")
        d["_file"] = f.name
        out.append(d)
    return out


def fmt_ns(x):
    if x is None:
        return "n/a"
    if x >= 1e6:
        return f"{x / 1e6:.3g} ms"
    if x >= 1e3:
        return f"{x / 1e3:.3g} us"
    return f"{x:.3g} ns"


def med(st):
    return None if not st else st.get("median")


def cell(st):
    if not st:
        return "n/a"
    return f"{fmt_ns(st['median'])} (MAD {fmt_ns(st['mad'])})" if st.get("unit", "ns") == "ns" else f"{st['median']:.3g} {st['unit']}"


def label(r, mode=None):
    name = f"{r['library']['name']} {r['library']['version']}"
    if r.get("kind") == "ceiling":
        name += " [ceiling]"
    return name + (f" / {mode}" if mode else "")


def md_table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


# ------------------------------------------------------------------ SVG

def bar_chart(path, title, rows, unit, log=False, banner=None):
    """rows = [(label, value)]; horizontal bars; log scale optional. Written as a standalone SVG."""
    rows = [(l, v) for l, v in rows if v is not None and (v > 0 or not log)]
    if not rows:
        return False
    rows.sort(key=lambda r: r[1])
    w, left, bar_h, gap, top = 900, 330, 20, 8, 60
    h = top + len(rows) * (bar_h + gap) + 30
    vmax = max(max(v for _, v in rows), 1e-12)
    vmin = min(v for _, v in rows)
    if log:
        lo = math.log10(vmin) - 0.3
        scale = lambda v: (math.log10(v) - lo) / (math.log10(vmax) - lo + 1e-9)
    else:
        scale = lambda v: v / vmax
    span = w - left - 150
    s = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}" role="img" aria-label="{html.escape(title)}">',
         f'<rect width="{w}" height="{h}" fill="#ffffff"/>',
         f'<text x="12" y="24" font-family="sans-serif" font-size="16" font-weight="bold" fill="#1a1a1a">{html.escape(title)}</text>',
         f'<text x="12" y="44" font-family="sans-serif" font-size="12" fill="#444444">{html.escape(banner or ("lower is better" + (", logarithmic axis" if log else "")))}</text>']
    for i, (l, v) in enumerate(rows):
        y = top + i * (bar_h + gap)
        bw = max(2, scale(v) * span)
        s.append(f'<text x="{left - 8}" y="{y + 14}" text-anchor="end" font-family="sans-serif" font-size="12" fill="#1a1a1a">{html.escape(l)}</text>')
        s.append(f'<rect x="{left}" y="{y}" width="{bw:.1f}" height="{bar_h}" fill="#2a6fb0"/>')
        s.append(f'<text x="{left + bw + 6:.1f}" y="{y + 14}" font-family="sans-serif" font-size="12" fill="#1a1a1a">{html.escape(fmt_ns(v) if unit == "ns" else f"{v:g} {unit}")}</text>')
    s.append("</svg>")
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text("\n".join(s) + "\n")
    return True


# ------------------------------------------------------------------ report

def semantic_mode(r):
    """The semantic mode to headline: 'plain' if present, else the first one."""
    sem = r.get("semantics") or {}
    return "plain" if "plain" in sem else (next(iter(sem)) if sem else None)


def build(results, img_dir, img_rel, fixture):
    L = []
    add = L.append
    add("# Comparison with other unit libraries")
    add("")
    add("Generated by `benchmarks/tools/report.py` from the raw files in `benchmarks/results/`. Do not edit by hand. Method and rules: [`docs/benchmarking.md`](../benchmarking.md).")
    add("")
    if fixture:
        add(FIXTURE_BANNER)
        add("")
    # --- run table
    add("## Runs included")
    add("")
    add(md_table(["Library", "Kind", "Runtime", "OS / CPU", "Date (UTC)", "Lockfile", "Corpus"],
                 [[label(r), r.get("kind"), f"{r['runtime']['name']} {r['runtime']['version']}",
                   f"{r['machine']['os']}; {r['machine']['cpu_model']}; {r['machine']['logical_cores']} cores; governor {r['machine'].get('governor') or 'unknown'}",
                   r["date_utc"], r.get("lockfile", "unknown"), r["corpus_id"]] for r in results]))
    add("")
    cpus = {(r["machine"]["cpu_model"], r["machine"]["os"]) for r in results}
    if len(cpus) > 1:
        add("> **Warning: these runs come from different machines.** Wall-clock figures across them are not comparable. The rule is one job on one machine (see the methodology).")
        add("")
    if len({r["corpus_id"] for r in results}) > 1:
        add("> **Warning: the runs used different corpus versions.** Accuracy and safety counts are not comparable.")
        add("")
    if any(r.get("lockfile") not in ("pinned",) for r in results if r.get("kind") == "library"):
        add("> Some library versions were not installed from a lockfile (`lockfile` column). Treat those rows as indicative only.")
        add("")
    add("GitHub-hosted runners are noisy. Python and JavaScript wall-clock figures are indicative; read the MAD (median absolute deviation) next to each median, and the raw samples in the JSON.")
    add("")
    charts = []

    # --- speed
    conv_ids = []
    for r in results:
        for mode_res in (r.get("performance") or {}).values():
            for cid in mode_res:
                if cid not in conv_ids:
                    conv_ids.append(cid)
    add("## Speed")
    add("")
    add("Median ns per conversion (MAD in brackets). **Scalar**: prepared conversion applied to one value, including the loop iteration of the host language (see the loop overhead rows). **One-shot**: parse a string such as `10 m/s` and convert it. **Batch**: ns per element for N values. Rows marked [ceiling] do no unit handling; they show what the language itself costs. `n/a` means the library has no such API or the runner could not run it (see the JSON `errors`).")
    add("")
    batch_sizes = sorted({int(n) for r in results for m in (r.get("performance") or {}).values()
                          for c in m.values() for n in (c.get("batch") or {})})
    for cid in conv_ids:
        add(f"### {cid}")
        add("")
        rows = []
        scalar_bar, batch_bar, oneshot_bar = [], [], []
        for r in results:
            for mode, mres in (r.get("performance") or {}).items():
                c = mres.get(cid)
                if c is None:
                    continue
                if c.get("unsupported"):
                    rows.append([label(r, mode), "unsupported", "", "", *[""] * len(batch_sizes)])
                    continue
                b = c.get("batch") or {}
                rows.append([label(r, mode), cell(c.get("scalar")), cell(c.get("loop_overhead")), cell(c.get("oneshot")),
                             *[cell(b.get(str(n))) for n in batch_sizes]])
                tag = label(r, mode)
                scalar_bar.append((tag, med(c.get("scalar"))))
                oneshot_bar.append((tag, med(c.get("oneshot"))))
                if batch_sizes:
                    batch_bar.append((tag, med(b.get(str(batch_sizes[-1])))))
        add(md_table(["Library / mode", "Scalar", "Loop overhead", "One-shot parse+convert", *[f"Batch {n:,}" for n in batch_sizes]], rows))
        add("")
        for key, data, title in (("scalar", scalar_bar, f"Scalar conversion, {cid}"),
                                 ("oneshot", oneshot_bar, f"One-shot parse and convert, {cid}"),
                                 ("batch", batch_bar, f"Batch of {batch_sizes[-1]:,} values, ns per element, {cid}" if batch_sizes else "")):
            fn = f"speed-{key}-{cid}.svg"
            if bar_chart(img_dir / fn, title, data, "ns", log=True, banner=FIXTURE_BANNER.strip("*") if fixture else None):
                charts.append(f"![{title}]({img_rel}/{fn})")
        add("")
    if charts:
        add("### Charts")
        add("")
        add("\n\n".join(charts))
        add("")

    # --- cold start
    add("## Prepare, startup and size")
    add("")
    rows = []
    for r in results:
        su = r.get("startup") or {}
        imp = su.get("import_ms")
        cold = []
        for mode, mres in (r.get("performance") or {}).items():
            for cid, c in mres.items():
                if c.get("prepare_cold"):
                    cold.append(c["prepare_cold"]["median"])
        rows.append([label(r), f"{imp['median']:.3g} ms" if imp else "n/a",
                     fmt_ns(sorted(cold)[len(cold) // 2]) if cold else "n/a",
                     f"{su['peak_rss_kb'] / 1024:.0f} MiB" if su.get("peak_rss_kb") else "n/a",
                     f"{su['package_bytes'] / 1e6:.2f} MB" if su.get("package_bytes") else "n/a"])
    add(md_table(["Library", "Import (extra over empty interpreter)", "Cold prepare (median over conversions)", "Peak RSS of the runner process", "Installed size"], rows))
    add("")
    add("Peak RSS covers the whole runner process including the corpus and all batch arrays, so compare it only between runs of the same language. For Rust, 'import' is the time to build the registry and 'installed size' is the runner executable.")
    add("")

    # --- accuracy
    libs = [r for r in results if r.get("kind") == "library" and r.get("semantics")]
    add("## Accuracy (against the exact rational truth)")
    add("")
    add("Every must-convert case has an exact rational expected result from an independent oracle. The error is the distance in ulp (steps between representable doubles) from the correctly rounded exact value. A result more than the tolerance away is counted as **wrong**. Cases a library cannot express are counted as **unsupported** and left out of the ulp statistics, so a library that answers few cases can look accurate: read the columns together.")
    add("")
    rows = []
    for r in libs:
        for mode, s in r["semantics"].items():
            a = s["accuracy"]
            rows.append([label(r, mode), a["cases"], a["answered"], a["unsupported"],
                         "n/a" if a["max_ulp"] is None else a["max_ulp"], "n/a" if a["median_ulp"] is None else a["median_ulp"],
                         a["bit_identical"], a["over_1_ulp"], a["wrong"]])
    add(md_table(["Library / semantic mode", "Cases", "Answered", "Unsupported", "Max ulp", "Median ulp", "Bit-identical", "> 1 ulp", f"Wrong (> {libs[0]['semantics'][next(iter(libs[0]['semantics']))]['accuracy']['tolerance_ulp'] if libs else 4} ulp)"], rows) if rows else "No library results.")
    add("")
    worst_rows = []
    for r in libs:
        for mode, s in r["semantics"].items():
            for w in s["accuracy"].get("worst", [])[:3]:
                if w.get("ulp"):
                    worst_rows.append([label(r, mode), w["id"], w["ulp"], w["got"], w["want"]])
    if worst_rows:
        add("Largest errors (up to 3 per library):")
        add("")
        add(md_table(["Library / mode", "Case", "ulp", "Got", "Correctly rounded truth"], worst_rows))
        add("")

    # --- coverage + safety
    add("## Coverage and safety matrix")
    add("")
    add("**Must convert** (correct / wrong value / error because unsupported) and **must refuse** (refused / silently accepted / not applicable). **Silently accepted** means the library returned a number for a request that is ambiguous or invalid. Any error counts as a refusal: the reason is not compared, except for Dimvexa (see below). A documented default (for example pint treating `ton` as the short ton) still counts as silently accepted because the request did not say which ton.")
    add("")
    rows = []
    for r in libs:
        for mode, s in r["semantics"].items():
            mc, mr = s["must_convert"], s["must_refuse"]
            rows.append([label(r, mode), mc["total"], mc["correct"], mc["wrong_value"], mc["unsupported"],
                         mr["total"], mr["refused"], f"**{mr['silently_accepted']}**" if mr["silently_accepted"] else "0", mr["not_applicable"]])
    add(md_table(["Library / mode", "Convert cases", "Correct", "Wrong value", "Unsupported", "Refuse cases", "Refused", "Silently accepted", "Not applicable"], rows) if rows else "No library results.")
    add("")
    for key, title, pick in (("correct", "Must-convert cases answered correctly (higher is better)", lambda s: s["must_convert"]["correct"]),
                             ("silent", "Silently accepted ambiguous or invalid requests (lower is better)", lambda s: s["must_refuse"]["silently_accepted"])):
        data = [(label(r, m), pick(s)) for r in libs for m, s in r["semantics"].items()]
        fn = f"safety-{key}.svg"
        note = "higher is better" if key == "correct" else "lower is better"
        if bar_chart(img_dir / fn, title, data, "", banner=FIXTURE_BANNER.strip("*") if fixture else note):
            add(f"![{title}]({img_rel}/{fn})")
            add("")
    # per-case refusal matrix
    add("### Per-request outcome for the must-refuse cases")
    add("")
    add("`ok` refused, `ACCEPTED` silently accepted (the number is shown), `-` not applicable.")
    add("")
    if libs:
        ids = []
        meta = {}
        for r in libs:
            for s in r["semantics"].values():
                for c in s["cases"]["must_refuse"]:
                    if c["id"] not in meta:
                        ids.append(c["id"])
                        meta[c["id"]] = c["category"]
        cols = [(r, m) for r in libs for m in r["semantics"]]
        by = {}
        for r, m in cols:
            for c in r["semantics"][m]["cases"]["must_refuse"]:
                by[(label(r, m), c["id"])] = c
        rows = []
        for i in sorted(ids):
            row = [i, meta[i]]
            for r, m in cols:
                c = by.get((label(r, m), i))
                row.append("" if c is None else {"refused": "ok", "not_applicable": "-"}.get(c["outcome"], f"ACCEPTED ({c.get('got', '')[:14]})"))
            rows.append(row)
        add(md_table(["Case", "Category", *[label(r, m) for r, m in cols]], rows))
        add("")
    # coverage
    add("### Unit coverage")
    add("")
    add("Units a library can parse, out of the coverage lists in the corpus (Dimvexa spellings, translated per library; see `benchmarks/translations/`). Parsing a unit does not prove its factor is right; the accuracy section checks values.")
    add("")
    cats = []
    for r in libs:
        for s in r["semantics"].values():
            for c in s["coverage"]:
                if c not in cats:
                    cats.append(c)
    rows = []
    for c in cats:
        row = [c]
        for r in libs:
            for m, s in r["semantics"].items():
                cv = s["coverage"].get(c)
                row.append("" if cv is None else f"{cv['known']}/{cv['total']}")
        rows.append(row)
    add(md_table(["List", *[label(r, m) for r in libs for m in r["semantics"]]], rows) if rows else "No library results.")
    add("")
    for r in libs:
        if r["library"]["name"] == "dimvexa":
            for m, s in r["semantics"].items():
                mr = s["must_refuse"]
                if "refused_for_intended_reason" in mr:
                    add(f"Dimvexa ({m}): {mr['refused_for_intended_reason']} of {mr['refused']} refusals carried the intended error code.")
                    add("")
                    break
    return "\n".join(L) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--results", default=str(ROOT / "results"))
    ap.add_argument("--out", default=str(OFFICIAL))
    args = ap.parse_args(argv)
    results = load(args.results)
    out = Path(args.out)
    fixtures = [r.get("fixture") for r in results]
    if any(fixtures) and not all(fixtures):
        raise SystemExit("refusing to mix fixture files with real results")
    fixture = bool(results) and all(fixtures)
    quick = [bool(r.get("parameters", {}).get("quick")) for r in results]
    if any(quick) and out.resolve() == OFFICIAL.resolve():
        raise SystemExit("refusing to publish --quick results (a smoke test, not a measurement); pass --out elsewhere")
    if any(quick) and not all(quick):
        raise SystemExit("refusing to mix --quick and full results")
    ids = {r.get("corpus_id") for r in results if not r.get("fixture")}
    if len(ids) > 1:
        raise SystemExit(f"result files come from different corpora ({sorted(map(str, ids))}); remove the stale ones")
    if fixture and out.resolve() == OFFICIAL.resolve():
        raise SystemExit("refusing to write fixture data to the official docs/benchmarks/comparison.md; pass --out elsewhere")
    out.parent.mkdir(parents=True, exist_ok=True)
    if not results:
        out.write_text("# Comparison with other unit libraries\n\n**No benchmark run has been published yet.** The runners are written (see [`docs/benchmarking.md`](../benchmarking.md), status table) but have not been run against the other libraries. "
                       "Until a dated run exists, nothing on this page and nothing in the README may claim that Dimvexa is faster or more accurate than any other library.\n")
        print(f"no result files in {args.results}; wrote notice to {out}")
        return 0
    img_dir = out.parent / "img"
    text = build(results, img_dir, "img", fixture)
    out.write_text(text)
    print(f"wrote {out} and charts in {img_dir} from {len(results)} result file(s){' (FIXTURE DATA)' if fixture else ''}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
